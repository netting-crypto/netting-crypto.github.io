const root = document.documentElement;
const langToggle = document.getElementById("langToggle");
const themeToggle = document.getElementById("themeToggle");
const themeIcon = themeToggle.querySelector(".theme-icon");
const localTime = document.getElementById("localTime");

const savedTheme = localStorage.getItem("pixel-profile-theme");
const preferredTheme = window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
setTheme(savedTheme || preferredTheme);

const savedLang = localStorage.getItem("pixel-profile-lang");
setLanguage(savedLang || "zh");

themeToggle.addEventListener("click", () => {
  setTheme(root.dataset.theme === "dark" ? "light" : "dark");
});

langToggle.addEventListener("click", () => {
  setLanguage(root.lang === "zh-CN" ? "en" : "zh");
});

function setTheme(theme) {
  root.dataset.theme = theme;
  themeIcon.textContent = theme === "dark" ? "☀" : "☾";
  localStorage.setItem("pixel-profile-theme", theme);
}

function setLanguage(lang) {
  const dictionary = translations[lang];
  root.lang = lang === "zh" ? "zh-CN" : "en";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) node.textContent = dictionary[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (dictionary[key]) node.placeholder = dictionary[key];
  });
  langToggle.textContent = lang === "zh" ? "EN" : "中";
  localStorage.setItem("pixel-profile-lang", lang);
}

function updateClock() {
  const formatter = new Intl.DateTimeFormat(root.lang === "zh-CN" ? "zh-CN" : "en-US", {
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
    hour12: false
  });
  localTime.textContent = formatter.format(new Date());
}
updateClock();
setInterval(updateClock, 1000);

const fishPet = document.getElementById("fishPet");
const fishChat = document.getElementById("fishChat");
const closeFish = document.getElementById("closeFish");
const fishForm = document.getElementById("fishForm");
const fishInput = document.getElementById("fishInput");
const fishMessages = document.getElementById("fishMessages");

function setFishOpen(open) {
  fishChat.classList.toggle("open", open);
  fishChat.setAttribute("aria-hidden", String(!open));
  if (open) fishInput.focus();
}

fishPet.addEventListener("click", () => setFishOpen(!fishChat.classList.contains("open")));
closeFish.addEventListener("click", () => setFishOpen(false));

fishForm.addEventListener("submit", (event) => {
  event.preventDefault();
  const text = fishInput.value.trim();
  if (!text) return;

  appendFishMessage(text, "user");
  fishInput.value = "";

  setTimeout(() => {
    appendFishMessage(getFishReply(text), "fish");
  }, 450);
});

function appendFishMessage(text, role) {
  const message = document.createElement("div");
  message.className = `fish-message ${role}`;
  const icon = document.createElement("span");
  icon.textContent = role === "fish" ? "🐟" : "👤";
  const body = document.createElement("p");
  body.textContent = text;
  message.append(icon, body);
  fishMessages.appendChild(message);
  fishMessages.scrollTop = fishMessages.scrollHeight;
}

function getFishReply(input) {
  const isEnglish = root.lang === "en";
  const text = input.toLowerCase();

  if (/生命|meaning of life/.test(text)) {
    return isEnglish ? "Food. The answer is always food." : "食物。答案永远是食物。";
  }

  if (/项目|project/.test(text)) {
    return isEnglish
      ? "Four quests: multi-omics, Feishu-Codex, conversation archaeology, and an application agent."
      : "目前四条主线：多组学、飞书-Codex、对话考古、批量投递 Agent。";
  }

  if (/工作|求职|job|career/.test(text)) {
    return isEnglish
      ? "He is looking for AI product roles where product judgment and agent execution meet."
      : "他在寻找偏 AI 产品与 Agent 落地的机会，尤其关注完整业务闭环。";
  }

  if (/你好|hi|hello|hey/.test(text)) {
    return isEnglish ? "blub blub. Welcome to netting.os." : "啵啵。欢迎来到 netting.os。";
  }

  if (/鱼|fish|hungry|饿/.test(text)) {
    return isEnglish ? "I accept snacks, stars, and GitHub issues." : "我接受零食、star，以及 GitHub issue。";
  }

  const zhReplies = [
    "这个问题值得先拆成输入、判断、动作和反馈。",
    "我只是一条鱼，但我觉得先做最小可运行版本。",
    "可以先看看项目区，也许那里藏着答案。",
    "啵。这个想法可以继续往下挖。"
  ];
  const enReplies = [
    "Break it into input, decision, action and feedback.",
    "I am only a fish, but I would ship the smallest working version first.",
    "Check the project quests. The answer may be hiding there.",
    "blub. That idea is worth digging into."
  ];
  const replies = isEnglish ? enReplies : zhReplies;
  return replies[Math.floor(Math.random() * replies.length)];
}

